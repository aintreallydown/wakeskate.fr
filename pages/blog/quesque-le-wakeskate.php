            <h3> 
                Pourquoi parlez du sens personnel ?
            </h3>

            <p>
                Tout simplement parce que c'est un peu ce qu'on recherche quand on part d'une idée général, cerner et réduire cette idée vers quelque chose de plus spécifique et personelle.
                Les termes générale, ca parle à tout le monde, mais c'est froid, c'est impersonnel, et ca ne reflète pas 
                vraiment ce que le wakeskate représente pour moi, et pour beaucoup de riders, c'est un sport qui est plus qu'un sport, 
                c'est une passion, c'est un mode de vie, c'est une communauté, c'est un état d'esprit, c'est une culture,
                c'est un art de vivre.
                Je pense qu'on est pas beaucoup à se poser la question de "Qu'est-ce que le wakeskate ?", et c'est pas plus mal, parce que justement, ca laisse place à l'interprétation, à la subjectivité, et à la diversité des expériences et des ressentis de chacun.
                Le wakeskate, c'est un peu comme une toile blanche, chacun est libre de se l'approprier comme il veux, d'en faire sa propre histoire, sa propre identité, sa propre vision, sa propre définition du wakeskate, et c'est ce qui fait la richesse et la beauté de ce sport,
                
                Peux etre que j'idéalise, mais le wakeskate me permet de m'évader, de me connecter avec la nature, de me défouler, de me dépasser, 
                de me faire des amis, de partager des moments inoubliables, de vivre des émotions fortes, de ressentir la liberté, la joie, la peur, 
                l'excitation, la frustration, la satisfaction, la fierté, et j'en passe.

                C'est aussi un sentiment d'appartenance unique, une communauté soudée, un esprit de camaraderie, de solidarité, d'entraide, de respect, de partage, de convivialité, et c'est ce qui fait que le wakeskate est plus qu'un sport pour moi, c'est une famille.
                Moi j'ai toujours été comme ca dans la vie de tout les jours, de proposer mon aide aux autres spontanément, de partager mes connaissances, de donner des conseils, 
                de motiver les autres, de les encourager, de les soutenir, et c'est ce que je retrouve dans le wakeskate, j'ai l'impression que les gens sont comme moi dans ce sport, et
                c'est ce qui me fait aimer ce sport encore plus, c'est ce qui me fait sentir chez moi et me donne envie de vivre plus de choses avec la vie.
            </p>

            
            <h2>Le grand saut </h2>
            
            <p>
                Sortir de sa zone de confort, c'est un peu le leitmotiv du wakeskate, c'est un sport qui nous pousse à 
                dépasser nos limites, à affronter nos peurs, à prendre des risques, à se challenger, à se surpasser, et 
                c'est ce qui fait que le wakeskate est aussi addictif et passionnant.
                C'est un sport qui nous apprend à tomber, à se relever, à persévérer tout comme le skateboard mais avec de l'eau en plus et c'a change beaucoup de chose, notament le rapport que l'on a 
                à la chute, à la peur de tomber, à la peur de se faire mal, à la peur de l'eau, et c'est ce qui fait que le wakeskate est aussi excitant et stimulant.
                C'est un sport qui nous apprend à gérer le stress, à contrôler nos émotions, à rester concentré, à être patient, à être humble, à être respectueux des autres, MAIS aussi de chuter de manière 
                trop marrante, et donc de rigoler de soi, de la manière dont on est tombé et de partager ce moment de rigolade avec 
                les autres, et c'est ce qui fait que le wakeskate est aussi fun et convivial.

            </p>
