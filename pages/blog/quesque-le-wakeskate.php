            <h2>Les mots de l'eau</h2>
            <p>
                Ici, on risque pas de parler de la <strong>"définition"</strong> du wakeskate, mais plutot de ce que ca représente pour moi en tant qu'humain, et en tant que rider qui aime tout ce qui est en rapport avec la glisse.
                Ce que je vous propose, c'est ma définition du wakeskate, ma définition personnel, ma vision de ce sport, ce que je ressent pendant les sessions et ce que je partage avec les copains.
