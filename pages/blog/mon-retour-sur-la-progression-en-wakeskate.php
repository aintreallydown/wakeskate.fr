            <h1>Introduction</h1>
            <p>Tout d'abord, pour remettre les choses dans leur contexte, j'ai commencé le skateboard classique bien
                avant le wakeskate, à quelques années d'intervalle. Je devais avoir 12 ans quand le skateboard
                classique est apparu comme une évidence, et que je devais pratiquer ce sport, le wakeskate, autour de
                mes
                14-15 ans. Je parle du skateboard classique car je me souviens de mes débuts, et ils étaient
                laborieux... Je pense que dans ce sport, il faut à la fois aimer être seul et accompagné. Un peu
                paradoxal, c'est vrai, mais les deux vont de pair. Je m'explique. Pourquoi aimer être seul, c'est quoi ?
                Tout simplement, parce que c'est une fatalité en skateboard : on fait ce sport pour soi-même, pour se
                faire
                progresser petit à petit, comme un artisan qui travaille sa matière dans son atelier. Il le fait pour
                lui, par passion,
                ou parce qu'on lui a transmis ce goût de travailler une forme, en répétant des gestes, pour que la
                forme soit
                esthétiquement équilibrée, harmonieuse, finie. Et c'est comme ça que l'artisan acquiert de l'aisance
                dans son travail, dans ses gestes, et
                par-dessus ça, qu'il aime son travail. Pourquoi cette analogie avec l'artisan ? Parce que le skateboard,
                c'est pareil. Certes, un atelier et des outils différents, mais un atelier quand même, et des outils
                aussi... le skatepark, la
                rue, le mobilier urbain, la création spontanée et l'inspiration vive.<br />Ensuite, pourquoi aimer être
                accompagné ? Je disais plus haut qu'il fallait aimer être seul, parce que l'on a souvent l'image d'un
                skateur seul. J'ai aussi cette image dans ma tête, parce que j'ai vécu ces moments seul, à essayer de
                répéter le même geste parfaitement ou avec plus de légèreté, et je travaille beaucoup mieux en solo.
                Maîtrise totale du rythme, pas de dispersion. Et aussi parce que, à un moment de concentration intense
                et
                d'efforts répétés vers un seul objectif, il existe un endroit très silencieux, où la perception du monde
                et du temps change, en phase avec soi-même. Le temps s'est arrêté, les problèmes se sont envolés,
                l'instant présent prend une autre dimension. Il n'y a qu'un bruit sourd autour de vous, il n'y a que
                vous, et vous seul en train de flotter dans l'instant présent. Je vous souhaite de vivre ça, ou si vous
                l'avez déjà vécu, alors vous savez pourquoi on y retourne... Et ces moments sont ponctués par des
                inconnus que l'on croise ou d'autres skateurs qui passent par là, qui sont dans la même bulle que vous,
                avec qui vous allez forcément partager, parce que la communication est facile dans ce sport, je trouve.
                Poser des questions à d'autres pratiquants est essentiel. Voilà pourquoi il faut aimer être accompagné :
                une
                astuce en plus ? Des idées qu'on n'avait pas vues ? De l'expérience à partager... C'est fou comment j'ai
                pu
                progresser simplement en discutant 5 minutes avec un skateur que je ne connaissais pas, qui a remarqué
                un
                truc que je ne faisais pas correctement, ou en regardant comment les gens plus forts arrivent à bouger
                dans
                l'espace, ou se meuvent en faisant un avec leur planche ?</p>

            <h1>L'artisan du skate</h1>
            <p><strong>La progression ?</strong> C'est de l'observation,
                de soi-même et des autres. Et c'est une vraie qualité que de savoir observer, de trouver les points
                pertinents, de savoir pourquoi on a réussi ou pourquoi l'autre a réussi. Ce n'est pas un tour de
                magie, c'est rationnel, c'est dans les faits et la bonne combinaison d'étapes bien mesurées. Savoir
                synthétiser
                les informations et les appliquer. C'est un travail de longue haleine, mais qui paye.
                Pour ma part, j'ai toujours été quelqu'un de très persévérant. Quand je veux quelque chose, je ne lâche
                rien
                jusqu'à ce que je l'obtienne. Cette détermination m'a beaucoup aidé dans ma progression en skate et en
                wakeskate. Le plus difficile, à mon avis, c'est que, dans cette capacité d'observation, en général,
                quand on réussit un trick, on a tendance à ne pas analyser ce qui a marché. On est content, on est fier,
                et on passe
                à autre chose. Alors que c'est justement dans ces moments-là qu'il faut se poser et réfléchir à ce qui
                a
                fonctionné, pour pouvoir le reproduire et l'améliorer. C'est un travail de patience et de rigueur, mais
                c'est essentiel pour progresser. Ce qu'il faut faire, c'est se connaître, savoir comment on
                fonctionne, quel est notre processus d'apprentissage le plus efficace. Pour moi par exemple, j'apprends
                à l'émotion, à l'énergie que j'ai donnée, l'effort que j'ai senti qu'il fallait donner. J'ai
                l'impression
                qu'avec le temps, l'effort devient cadré, mieux organisé, et il paraît de moins en moins comme un
                effort, mais plus comme un jeu. Et par voie de conséquence, on oublie même que l'effort a été fourni.
                Mais j'apprends aussi en faisant tout simplement du crash test. Je trouve cette méthode très efficace,
                parce que
                j'ai l'impression que c'est en tombant qu'on apprend le mieux. En tombant, on comprend ce qui n'a pas
                marché, on ressent les limites de notre corps et de notre technique, et on peut ajuster en conséquence.
                C'est un processus d'essais et d'erreurs, mais c'est aussi ce qui rend le skate si passionnant. On est
                toujours en train de repousser ses limites, de tester de nouvelles choses, et c'est ça qui fait que le
                skate est un sport si vivant et si excitant.</p>

            <h1>Conclusion</h1>
            <p>En conclusion, je dirais que la progression en skate et en wakeskate est un processus complexe et
                multifacette, mais à nous de le rendre plus simple. Cela demande de la patience, de la rigueur, et une
                bonne dose de passion. C'est un sport
                qui nous apprend beaucoup sur nous-mêmes, sur nos limites, et sur notre capacité à les dépasser. Et
                c'est
                aussi un sport qui nous permet de nous exprimer, de créer, et de partager des moments uniques avec
                d'autres passionnés. Alors, si vous êtes débutant ou si vous cherchez à progresser, n'hésitez pas à
                prendre le temps d'observer, de réfléchir, et de vous connaître. Et surtout, n'oubliez pas de prendre
                du plaisir dans ce que vous faites, car c'est ça qui rend le skate si spécial.</p>


